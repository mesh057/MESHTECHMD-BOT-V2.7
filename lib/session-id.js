'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const zlib = require('zlib');

const SESSION_ID_PREFIX = 'MeshTech~v2~';
const MAX_SESSION_BYTES = 20 * 1024 * 1024;
const MAX_SESSION_FILES = 512;

function normalizePhoneNumber(value) {
    const digits = String(value || '').replace(/\D/g, '');
    if (!/^\d{8,15}$/.test(digits)) throw new Error('A valid international phone number is required.');
    return digits;
}
function assertCredentialNumber(creds, expectedNumber) {
    const identity = creds?.me?.id || creds?.me?.jid;
    if (!identity) return;
    const identityDigits = String(identity).split('@')[0].split(':')[0].replace(/\D/g, '');
    if (/^\d{8,15}$/.test(identityDigits) && identityDigits !== expectedNumber) {
        throw new Error(`Auth credentials belong to ${identityDigits}, not ${expectedNumber}.`);
    }
}

function collectFiles(rootDir, currentDir = rootDir, files = {}) {
    for (const entry of fs.readdirSync(currentDir, { withFileTypes: true })) {
        if (entry.isSymbolicLink()) continue;
        const absolute = path.join(currentDir, entry.name);
        const relative = path.relative(rootDir, absolute).split(path.sep).join('/');
        if (entry.isDirectory()) {
            collectFiles(rootDir, absolute, files);
            continue;
        }
        if (!entry.isFile()) continue;
        const content = fs.readFileSync(absolute);
        files[relative] = content.toString('base64');
        if (Object.keys(files).length > MAX_SESSION_FILES) {
            throw new Error(`Session contains more than ${MAX_SESSION_FILES} files.`);
        }
    }
    return files;
}

function canonicalFiles(files) {
    return Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
}

function checksumFiles(files) {
    return crypto.createHash('sha256').update(JSON.stringify(canonicalFiles(files))).digest('hex');
}

function createSessionId(authDir, phoneNumber) {
    const credsPath = path.join(authDir, 'creds.json');
    if (!fs.existsSync(credsPath)) return null;

    let creds;
    try {
        creds = JSON.parse(fs.readFileSync(credsPath, 'utf8'));
    } catch (_) {
        throw new Error('The saved credentials are not valid JSON.');
    }
    if (!creds || creds.registered !== true) {
        throw new Error('The WhatsApp account is not fully registered yet. Pair it first.');
    }

    const files = canonicalFiles(collectFiles(authDir));
    if (!Object.keys(files).length || !files['creds.json']) return null;
    const payload = {
        version: 2,
        number: normalizePhoneNumber(phoneNumber),
        files,
        checksum: checksumFiles(files),
    };
    const serialized = Buffer.from(JSON.stringify(payload));
    if (serialized.length > MAX_SESSION_BYTES) throw new Error('The auth state is too large to export safely.');
    return SESSION_ID_PREFIX + zlib.gzipSync(serialized, { level: 9 }).toString('base64url');
}

function decodeSessionId(value) {
    const sessionId = String(value || '').trim();
    if (!sessionId.startsWith(SESSION_ID_PREFIX)) {
        if (sessionId.startsWith('MeshTech~')) {
            throw new Error('This is a legacy V2.5 session ID. It contains credentials only and is not a complete V2.7 auth backup. Pair the account again or generate a V2.7 recovery ID.');
        }
        throw new Error('SESSION_ID must be generated by the V2.7 .session command.');
    }

    const encoded = sessionId.slice(SESSION_ID_PREFIX.length);
    if (!encoded || encoded.length > MAX_SESSION_BYTES * 2) throw new Error('SESSION_ID is empty or exceeds the size limit.');

    let payload;
    try {
        const compressed = Buffer.from(encoded, 'base64url');
        const raw = zlib.gunzipSync(compressed, { maxOutputLength: MAX_SESSION_BYTES });
        payload = JSON.parse(raw.toString('utf8'));
    } catch (error) {
        throw new Error(`SESSION_ID cannot be decoded: ${error.message}`);
    }

    if (!payload || payload.version !== 2 || typeof payload.files !== 'object' || Array.isArray(payload.files)) {
        throw new Error('SESSION_ID has an unsupported format.');
    }
    const number = normalizePhoneNumber(payload.number);
    const files = canonicalFiles(payload.files);
    if (Object.keys(files).length > MAX_SESSION_FILES || !files['creds.json']) {
        throw new Error('SESSION_ID is missing required auth files or exceeds the file limit.');
    }
    if (checksumFiles(files) !== payload.checksum) throw new Error('SESSION_ID integrity check failed.');

    let totalBytes = 0;
    for (const [relative, base64Content] of Object.entries(files)) {
        if (typeof base64Content !== 'string' || path.isAbsolute(relative) || relative.split('/').some(part => !part || part === '.' || part === '..')) {
            throw new Error('SESSION_ID contains an invalid file path or file value.');
        }
        const content = Buffer.from(base64Content, 'base64');
        if (content.toString('base64') !== base64Content) throw new Error('SESSION_ID contains invalid base64 file data.');
        totalBytes += content.length;
        if (totalBytes > MAX_SESSION_BYTES) throw new Error('SESSION_ID expands beyond the allowed size.');
    }

    const creds = JSON.parse(Buffer.from(files['creds.json'], 'base64').toString('utf8'));
    if (creds.registered !== true) throw new Error('SESSION_ID does not contain a registered WhatsApp account.');
    assertCredentialNumber(creds, number);
    return { number, files };
}

function getSessionIdNumber(value) {
    try {
        return decodeSessionId(value).number;
    } catch (_) {
        return null;
    }
}

function restoreSessionId(value, targetDir, expectedNumber) {
    const payload = decodeSessionId(value);
    const normalizedExpected = normalizePhoneNumber(expectedNumber);
    if (payload.number !== normalizedExpected) {
        throw new Error(`SESSION_ID belongs to ${payload.number}, not ${normalizedExpected}.`);
    }

    const resolvedTarget = path.resolve(targetDir);
    if (fs.existsSync(resolvedTarget) && fs.readdirSync(resolvedTarget).length > 0) {
        throw new Error('Refusing to overwrite an existing auth directory with SESSION_ID data.');
    }

    const preparedFiles = Object.entries(payload.files).map(([relative, base64Content]) => {
        const absolute = path.resolve(resolvedTarget, ...relative.split('/'));
        if (!absolute.startsWith(resolvedTarget + path.sep)) throw new Error('SESSION_ID contains a path outside the auth directory.');
        return { relative, content: Buffer.from(base64Content, 'base64') };
    });

    const stagingDir = `${resolvedTarget}.restore-${process.pid}-${crypto.randomBytes(8).toString('hex')}`;
    fs.mkdirSync(stagingDir, { recursive: true, mode: 0o700 });
    try {
        for (const { relative, content } of preparedFiles) {
            const absolute = path.resolve(stagingDir, ...relative.split('/'));
            const stagingRoot = path.resolve(stagingDir) + path.sep;
            if (!absolute.startsWith(stagingRoot)) throw new Error('SESSION_ID contains a path outside the auth directory.');
            fs.mkdirSync(path.dirname(absolute), { recursive: true, mode: 0o700 });
            fs.writeFileSync(absolute, content, { flag: 'wx', mode: 0o600 });
        }
        if (fs.existsSync(resolvedTarget)) {
            if (fs.readdirSync(resolvedTarget).length > 0) {
                throw new Error('Refusing to overwrite an existing auth directory with SESSION_ID data.');
            }
            fs.rmdirSync(resolvedTarget);
        }
        fs.renameSync(stagingDir, resolvedTarget);
    } catch (error) {
        fs.rmSync(stagingDir, { recursive: true, force: true });
        throw error;
    }
    return { number: payload.number, fileCount: preparedFiles.length };
}

module.exports = {
    SESSION_ID_PREFIX,
    createSessionId,
    decodeSessionId,
    getSessionIdNumber,
    restoreSessionId,
};
